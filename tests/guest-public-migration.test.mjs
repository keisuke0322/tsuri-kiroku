import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFile,readdir} from 'node:fs/promises';
const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
for(const file of (await readdir('drizzle')).filter(f=>f.endsWith('.sql')&&f<'0008').sort())db.exec(await readFile(`drizzle/${file}`,'utf8'));
db.prepare('INSERT INTO profiles(user_id,display_name) VALUES (?,?)').run('owner','釣り人');
db.prepare('INSERT INTO catches(date,location,species,count,owner_id) VALUES (?,?,?,?,?)').run('2026-10-08','海岸','アジ',2,'owner');
const before=db.prepare('SELECT * FROM catches').get();
db.exec(await readFile('drizzle/0008_guest_public.sql','utf8'));
const {guest_public,...after}=db.prepare('SELECT * FROM catches').get();
assert.deepEqual(after,{...before});assert.equal(guest_public,0,'Existing posts are never automatically public');
db.prepare('INSERT INTO catches(date,location,species,count,owner_id) VALUES (?,?,?,?,?)').run('2026-10-09','海岸','サバ',3,'owner');
assert.equal(db.prepare('SELECT guest_public FROM catches WHERE id=2').get().guest_public,0);
for(const value of [null,-1,2,'true'])assert.throws(()=>db.prepare('UPDATE catches SET guest_public=? WHERE id=1').run(value));
db.prepare('UPDATE catches SET guest_public=1 WHERE id=1').run();
assert.equal(db.prepare('SELECT guest_public FROM catches WHERE id=1').get().guest_public,1);
db.close();
console.log('Guest publication migration preserved existing posts and defaults with explicit opt-in only.');
